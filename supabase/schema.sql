-- ---------- Document number sequences ----------
create sequence if not exists po_no_seq;
create sequence if not exists gate_no_seq;
create sequence if not exists grn_no_seq;
create sequence if not exists batch_no_seq;
create sequence if not exists invoice_no_seq;

-- ---------- Settings / masters (scrap types, grades, divisions, company) ----------
create table if not exists settings (
  key        text primary key,
  value      jsonb not null,
  updated_at timestamptz not null default now()
);

-- ---------- Purchase cycle ----------
create table if not exists purchase_orders (
  id          bigint generated by default as identity primary key,
  po_no       text unique,
  date        date not null default current_date,
  vendor      text not null,
  scrap_type  text not null,
  qty_kg      numeric(14,3) not null check (qty_kg > 0),
  rate_kg     numeric(14,3) not null check (rate_kg >= 0),
  remarks     text,
  closed      boolean not null default false,
  created_at  timestamptz not null default now()
);

create table if not exists containers (
  id               bigint generated by default as identity primary key,
  po_id            bigint not null references purchase_orders(id) on delete cascade,
  container_no     text not null,
  expected_arrival date,
  status           text not null default 'pending' check (status in ('pending','gate-in','received')),
  created_at       timestamptz not null default now()
);
create index if not exists containers_po_idx on containers(po_id);

create table if not exists gate_entries (
  id           bigint generated by default as identity primary key,
  gate_no      text unique,
  date         date not null default current_date,
  time         text,
  po_id        bigint references purchase_orders(id) on delete restrict,
  po_no        text,
  container_id bigint references containers(id) on delete restrict,
  container_no text,
  vendor       text,
  vehicle_no   text,
  gross_kg     numeric(14,3),
  tare_kg      numeric(14,3),
  status       text not null default 'in-yard' check (status in ('in-yard','grn-done')),
  created_at   timestamptz not null default now()
);

create table if not exists grns (
  id          bigint generated by default as identity primary key,
  grn_no      text unique,
  date        date not null default current_date,
  po_id       bigint references purchase_orders(id) on delete restrict,
  po_no       text,
  gate_id     bigint references gate_entries(id) on delete restrict,
  gate_no     text,
  vendor      text not null,
  scrap_type  text not null,
  weight_kg   numeric(14,3) not null check (weight_kg > 0),
  rate_kg     numeric(14,3) not null check (rate_kg >= 0),
  amount      numeric(16,2) not null,
  paid_amount numeric(16,2) not null default 0,
  remarks     text,
  created_at  timestamptz not null default now()
);

-- ---------- Production ----------
create table if not exists production_batches (
  id             bigint generated by default as identity primary key,
  batch_no       integer unique,
  date           date not null default current_date,
  division       text not null,
  unit           text not null,
  scrap_inputs   jsonb not null default '[]'::jsonb,  -- [{type, weight_kg}]
  start_time     text,
  end_time       text,
  skelner        jsonb,                              -- {start_time, end_time, additions:[{name, weight_kg}]}
  grade          text not null,
  output_kg      numeric(14,3) not null,
  dross_kg       numeric(14,3) default 0,
  total_input_kg numeric(14,3) not null,
  recovery_pct   numeric(7,3) not null,
  remarks        text,
  created_at     timestamptz not null default now()
);

-- ---------- Store ----------
create table if not exists store_transactions (
  id         bigint generated by default as identity primary key,
  date       date not null default current_date,
  type       text not null check (type in ('in','out')),
  item       text not null,
  qty        numeric(14,3) not null check (qty > 0),
  unit       text not null default 'kg',
  slip_no    text,
  party      text,
  remarks    text,
  created_at timestamptz not null default now()
);

-- ---------- Sales ----------
create table if not exists sales (
  id          bigint generated by default as identity primary key,
  invoice_no  text unique,
  date        date not null default current_date,
  customer    text not null,
  grade       text not null,
  weight_kg   numeric(14,3) not null check (weight_kg > 0),
  rate_kg     numeric(14,3) not null check (rate_kg >= 0),
  amount      numeric(16,2) not null,
  paid_amount numeric(16,2) not null default 0,
  vehicle_no  text,
  remarks     text,
  created_at  timestamptz not null default now()
);

-- ---------- Payments (against GRNs = paid out, against Sales = received) ----------
create table if not exists payments (
  id         bigint generated by default as identity primary key,
  date       date not null default current_date,
  ref_type   text not null check (ref_type in ('grn','sale')),
  ref_id     bigint not null,
  ref_no     text,
  party      text not null,
  amount     numeric(16,2) not null check (amount > 0),
  mode       text,
  note       text,
  created_at timestamptz not null default now()
);
create index if not exists payments_ref_idx on payments(ref_type, ref_id);

-- ---------- Auto document numbers ----------
-- One small trigger function per table (PL/pgSQL can't reference a column the table doesn't have).
create or replace function set_po_no() returns trigger language plpgsql as $$
begin
  if new.po_no is null then new.po_no := 'PO-' || lpad(nextval('po_no_seq')::text, 4, '0'); end if;
  return new;
end $$;
create or replace function set_gate_no() returns trigger language plpgsql as $$
begin
  if new.gate_no is null then new.gate_no := 'GN-' || lpad(nextval('gate_no_seq')::text, 4, '0'); end if;
  return new;
end $$;
create or replace function set_grn_no() returns trigger language plpgsql as $$
begin
  if new.grn_no is null then new.grn_no := 'GRN-' || lpad(nextval('grn_no_seq')::text, 4, '0'); end if;
  return new;
end $$;
create or replace function set_batch_no() returns trigger language plpgsql as $$
begin
  if new.batch_no is null then new.batch_no := nextval('batch_no_seq'); end if;
  return new;
end $$;
create or replace function set_invoice_no() returns trigger language plpgsql as $$
begin
  if new.invoice_no is null then new.invoice_no := 'INV-' || lpad(nextval('invoice_no_seq')::text, 4, '0'); end if;
  return new;
end $$;

drop trigger if exists trg_po_no on purchase_orders;
create trigger trg_po_no before insert on purchase_orders for each row execute function set_po_no();
drop trigger if exists trg_gate_no on gate_entries;
create trigger trg_gate_no before insert on gate_entries for each row execute function set_gate_no();
drop trigger if exists trg_grn_no on grns;
create trigger trg_grn_no before insert on grns for each row execute function set_grn_no();
drop trigger if exists trg_batch_no on production_batches;
create trigger trg_batch_no before insert on production_batches for each row execute function set_batch_no();
drop trigger if exists trg_invoice_no on sales;
create trigger trg_invoice_no before insert on sales for each row execute function set_invoice_no();

-- ---------- Access rules ----------
-- No login is used, so the public (anon) key may read and write every table.
-- Anyone who has the app link can view and edit data. To lock it down later,
-- enable Supabase Auth and replace "using (true)" with "using (auth.role() = 'authenticated')".
do $$
declare t text;
begin
  foreach t in array array['settings','purchase_orders','containers','gate_entries','grns',
                           'production_batches','store_transactions','sales','payments']
  loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "app full access" on %I', t);
    execute format('create policy "app full access" on %I for all to anon, authenticated using (true) with check (true)', t);
  end loop;
end $$;

grant usage on schema public to anon, authenticated;
grant all on all tables in schema public to anon, authenticated;
grant all on all sequences in schema public to anon, authenticated;
